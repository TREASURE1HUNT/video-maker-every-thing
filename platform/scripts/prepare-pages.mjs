import {cp,mkdir,writeFile,readFile} from 'node:fs/promises';
import path from 'node:path';
const source=path.resolve(import.meta.dirname,'../dist'),dest=path.resolve(import.meta.dirname,'../../pages-dist');
await mkdir(dest,{recursive:true});await cp(source,dest,{recursive:true,filter:p=>!/[\\/](server|\.openai)([\\/]|$)/.test(p)});
const security=await readFile(path.resolve(import.meta.dirname,'../server/security-headers.mjs'),'utf8');
const gateway=await readFile(path.resolve(import.meta.dirname,'../server/pages-gateway.mjs'),'utf8');
if(!gateway.startsWith("import {secureResponse} from './security-headers.mjs';"))throw Error('Unexpected gateway dependency');
await writeFile(path.join(dest,'_worker.js'),security.replace(/^export /gm,'')+'\n'+gateway.replace(/^import [^\n]+\n/,''));
await writeFile(path.join(dest,'_routes.json'),JSON.stringify({version:1,include:['/*'],exclude:[]}));
console.log('PAGES_GATEWAY_BUILD_OK');
